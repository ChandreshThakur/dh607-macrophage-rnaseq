def md5sum(path: Path, block_size: int = 1024 * 1024) -> str:
    digest = hashlib.md5()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(block_size), b""):
            digest.update(block)
    return digest.hexdigest()


def gzip_ok(path: Path, block_size: int = 1024 * 1024) -> bool:
    try:
        with gzip.open(path, "rb") as handle:
            while handle.read(block_size):
                pass
        return True
    except (OSError, EOFError):
        return False


def build_manifest(root: Path) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    local_by_md5: dict[str, list[str]] = {}
    for relative, (expected_md5, source) in EXPECTED.items():
        path = root / relative
        exists = path.is_file()
        local_md5 = md5sum(path) if exists else ""
        if local_md5:
            local_by_md5.setdefault(local_md5, []).append(relative)
        rows.append(
            {
                "filename": path.name,
                "relative_path": relative,
                "size_bytes": path.stat().st_size if exists else 0,
                "local_md5": local_md5,
                "authoritative_md5": expected_md5,
                "source_url": source,
                "exists": exists,
                "gzip_integrity": gzip_ok(path) if exists else False,
                "checksum_verified": exists and local_md5 == expected_md5,
            }
        )
    frame = pd.DataFrame(rows)
    frame["duplicate_content"] = frame["local_md5"].map(
        lambda value: len(local_by_md5.get(value, [])) > 1 if value else False
    )
    frame["verification_status"] = frame.apply(
        lambda row: "verified" if row["exists"] and row["gzip_integrity"] and row["checksum_verified"] else "failed",
        axis=1,
    )
    return frame


def _report(root: Path, manifest: pd.DataFrame, fastq: pd.DataFrame, metadata: pd.DataFrame,
            completeness: pd.DataFrame, count_check: dict[str, object], cqn_check: dict[str, object],
            gene_metadata: pd.DataFrame) -> str:
    verified = int((manifest["verification_status"] == "verified").sum())
    complete = int(completeness["one_sample_each"].sum())
    conditions = condition_summary(metadata)
    condition_lines = "\n".join(
        f"- {r.condition} = {r.condition_name} (IFNg={r.IFNg}, SL1344={r.SL1344}): {r.n_samples} samples / {r.n_donors} donors"
        for r in conditions.itertuples(index=False)
    )
    return f"""# Data audit

Generated by `python scripts/run_data_audit.py`; all claims below derive from the supplied files.

## File integrity

- Expected files found: {int(manifest['exists'].sum())}/12.
- MD5- and gzip-verified against the cited Zenodo records: {verified}/12.
- Duplicate file content detected: {bool(manifest['duplicate_content'].any())}.
- Authoritative sources: [training FASTQs]({ZENODO_FASTQ}) and [published matrices]({ZENODO_PUBLISHED}).
- Full checksums, byte sizes, source URLs, and per-file status are in `data/manifests/file_manifest.csv`.

## FASTQ structure

- Files parsed: {len(fastq)}; total records across mate files: {int(fastq['read_count'].sum()):,}.
- Malformed records: {int(fastq['malformed_records'].sum()):,}.
- Pairing-ID mismatches: {int(fastq['pairing_id_mismatches'].sum() / 2):,} paired positions (the summary repeats each mismatch on both mates).
- All mate read counts equal: {bool(fastq['mate_read_count_equal'].all())}.
- All FASTQs readable to gzip EOF: {bool(fastq['gzip_readable'].all())}.
- These FASTQs contain chromosome-21-selected reads only and include A and C, not the full factorial design.

## Published RNA-seq design

- Sample metadata: {len(metadata)} rows, {metadata['sample_id'].nunique()} unique sample IDs, {metadata['donor'].nunique()} donors.
- Donors with exactly one A/B/C/D sample: {complete}/{metadata['donor'].nunique()}.
{condition_lines}
- Recorded technical covariates include `library_pool`, `chemistry`, `rna_auto`, replicate, culture/differentiation dates, and purity measures.

## Matrices

- Raw-count orientation and dimensions: {count_check['orientation']}, {count_check['n_genes']:,} genes x {count_check['n_samples']} samples.
- Count/sample identifier sets match: {count_check['sample_id_sets_match']}; order matches metadata: {count_check['sample_order_matches_metadata']}.
- Raw-count missing/negative/non-integer entries: {count_check['missing_values']}/{count_check['negative_values']}/{count_check['noninteger_values']}.
- CQN dimensions: {cqn_check['n_genes']:,} genes x {cqn_check['n_samples']} samples; IDs and order match raw counts: {cqn_check['same_gene_ids_and_order_as_counts'] and cqn_check['same_sample_ids_and_order_as_counts']}.
- Gene metadata: {len(gene_metadata):,} rows, unique IDs={gene_metadata['gene_id'].is_unique}; identifiers are Ensembl gene IDs without version suffixes.
- The CQN matrix is normalized continuous expression and is not treated as raw counts.

## Scope and limitations

Passing integrity checks establish bitwise agreement with the Zenodo files, not biological validity. FastQC/MultiQC and Salmon require external command-line tools; their availability and execution are tracked separately. No raw file was modified.
"""


def run(root: Path) -> None:
    (root / "data/manifests").mkdir(parents=True, exist_ok=True)
    (root / "results/tables").mkdir(parents=True, exist_ok=True)
    (root / "docs").mkdir(parents=True, exist_ok=True)

    manifest = build_manifest(root)
    manifest.to_csv(root / "data/manifests/file_manifest.csv", index=False)

    fastq_rows: list[dict[str, object]] = []
    for donor in ("eipl", "fikt"):
        for condition in ("A", "C"):
            left = root / f"data/raw_fastq/{donor}_{condition}.1.fastq.gz"
            right = root / f"data/raw_fastq/{donor}_{condition}.2.fastq.gz"
            stats = validate_pair(left, right)
            fastq_rows.extend(item.to_dict() for item in stats)
    fastq = pd.DataFrame(fastq_rows)
    fastq.to_csv(root / "results/tables/fastq_read_summary.csv", index=False)

    published = root / "data/published"
    metadata = read_metadata(published / "RNA_sample_metadata.txt.gz")
    summary = condition_summary(metadata)
    summary.to_csv(root / "results/tables/sample_summary.csv", index=False)
    completeness = donor_completeness(metadata)
    completeness.to_csv(root / "results/tables/donor_condition_completeness.csv", index=False)

    counts = read_expression(published / "RNA_count_matrix.txt.gz")
    cqn = read_expression(published / "RNA_cqn_matrix.txt.gz")
    gene_metadata = pd.read_csv(published / "RNA_gene_metadata.txt.gz", sep="\t")
    count_check = validate_count_matrix(counts, metadata)
    cqn_check = validate_cqn_matrix(cqn, counts)
    matrix_rows = [
        {"matrix": "raw_counts", **count_check},
        {"matrix": "cqn", **cqn_check},
    ]
    pd.DataFrame(matrix_rows).to_csv(root / "results/tables/matrix_validation_summary.csv", index=False)
    (root / "docs/data_audit.md").write_text(
        _report(root, manifest, fastq, metadata, completeness, count_check, cqn_check, gene_metadata),
        encoding="utf-8",
    )


if __name__ == "__main__":
    run(Path.cwd())

